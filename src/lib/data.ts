export function getProperty(slug: string) {
  return properties.find((property) => property.slug === slug);
}

export function getNeighborhood(slug: string) {
  return neighborhoods.find((neighborhood) => neighborhood.slug === slug);
}

export function getArticle(slug: string) {
  return articles.find((article) => article.slug === slug);
}

export function getAgent(id: string) {
  return agents.find((agent) => agent.id === id);
}

export function homesIn(slug: string) {
  return properties.filter((property) => property.neighborhoodSlug === slug);
}

export function similarTo(slug: string) {
  const current = getProperty(slug);
  if (!current) return [];
  return properties
    .filter(
      (property) =>
        property.slug !== slug &&
        (property.region === current.region || property.type === current.type),
    )
    .slice(0, 3);
}

export function compactPlace(value: string) {
  return value.toLowerCase().replace(/[^a-z]/g, "");
}

export function regionByName(name: string) {
  const target = compactPlace(name);
  return ghanaRegions.find((region) => compactPlace(region.name) === target);
}

export function regionCounts() {
  return ghanaRegions.map((region) => ({
    ...region,
    count: properties.filter((property) => property.region === region.name).length,
  }));
}
